#!/usr/bin/env python3
"""Fetch the official ShadowTraffic docs and split them into references/docs/.

The public repo intentionally does not bundle ShadowTraffic's documentation.
This script downloads the LLM-friendly bundle published by ShadowTraffic,
splits it into one Markdown file per docs page, and writes a provenance README.

Usage:
    python3 scripts/fetch_docs.py
    python3 scripts/fetch_docs.py --ref v2.5.1 --output references/docs
"""

from __future__ import annotations

import argparse
import re
import sys
import urllib.error
import urllib.request
from pathlib import Path

DEFAULT_URL = (
    "https://raw.githubusercontent.com/ShadowTraffic/shadowtraffic-ai-context/"
    "{ref}/markdown-docs/docs.md"
)
USER_AGENT = "shadowtraffic-skill-docs-fetcher/1.0"


def fetch(url: str) -> str:
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read().decode("utf-8")


def split_pages(bundle: str) -> list[tuple[str, str]]:
    # Page boundaries look like: "# functions/uuid.md"
    parts = re.split(r"(?m)^# ([^\n]+\.md)\s*$", bundle)
    if len(parts) < 3:
        raise ValueError("downloaded bundle does not contain '# <page>.md' headings")

    pages: list[tuple[str, str]] = []
    for index in range(1, len(parts), 2):
        name = parts[index].strip()
        body = parts[index + 1].strip()
        relative = Path(name)
        if relative.is_absolute() or ".." in relative.parts:
            print(f"skip unsafe path: {name}", file=sys.stderr)
            continue
        # The upstream bundle uses "[Badges]" as a placeholder for the docs UI.
        body = re.sub(r"(?m)^\[Badges\]\s*$\n?", "", body)
        pages.append((name, body.rstrip() + "\n"))
    return pages


def write_readme(output: Path, ref: str, count: int) -> None:
    output.joinpath("README.md").write_text(
        "# Official ShadowTraffic docs\n\n"
        "Generated by `scripts/fetch_docs.py` — do not edit by hand.\n\n"
        f"- Source: `https://github.com/ShadowTraffic/shadowtraffic-ai-context` (`{ref}`)\n"
        "- Upstream docs: https://docs.shadowtraffic.io\n"
        f"- Pages: {count}\n\n"
        "This directory is git-ignored. ShadowTraffic's documentation remains the\n"
        "property of ShadowTraffic; it is downloaded locally for reference only.\n",
        encoding="utf-8",
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ref", default="master", help="git ref of the AI context repo")
    parser.add_argument(
        "--output",
        default="references/docs",
        type=Path,
        help="destination directory (default: references/docs)",
    )
    parser.add_argument(
        "--url",
        default=None,
        help="override the full bundle URL (useful for offline mirrors)",
    )
    args = parser.parse_args()

    url = args.url or DEFAULT_URL.format(ref=args.ref)
    print(f"fetching {url}")
    try:
        bundle = fetch(url)
    except (urllib.error.URLError, TimeoutError) as error:
        print(f"download failed: {error}", file=sys.stderr)
        return 1

    pages = split_pages(bundle)
    args.output.mkdir(parents=True, exist_ok=True)
    for name, body in pages:
        destination = args.output / name
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(body, encoding="utf-8")

    write_readme(args.output, args.ref, len(pages))
    print(f"wrote {len(pages)} pages to {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
